// GAME 4: SHIFTING ARROWS
// ============================================================================
function ShiftingArrowsGame() {
  const directions = ['UP', 'DOWN', 'LEFT', 'RIGHT'];
  const arrowChars = { UP: '↑', DOWN: '↓', LEFT: '←', RIGHT: '→' };
  const [targetDir, setTargetDir] = useState('UP');
  const [currentArrow, setCurrentArrow] = useState('UP');
  const [score, setScore] = useState(0);
  const [isPlaying, setIsPlaying] = useState(false);
  const [time, setTime] = useState(10);
  const timerRef = useRef(null);

  const nextRound = () => {
    setTargetDir(directions[Math.floor(Math.random() * 4)]);
    setCurrentArrow(directions[Math.floor(Math.random() * 4)]);
  };

  const handleAnswer = (matches) => {
    if (!isPlaying) return;
    const isCorrect = (targetDir === currentArrow) === matches;
    if (isCorrect) {
      setScore(s => s + 1);
      playSynthTone(500);
    } else {
      playSynthTone(180);
    }
    nextRound();
  };

  const startTest = () => {
    setScore(0);
    setTime(10);
    setIsPlaying(true);
    nextRound();
    if (timerRef.current) clearInterval(timerRef.current);
    timerRef.current = setInterval(() => {
      setTime(t => {
        if (t <= 1) {
          clearInterval(timerRef.current);
          setIsPlaying(false);
          return 0;
        }
        return t - 1;
      });
    }, 1000);
  };

  useEffect(() => { return () => clearInterval(timerRef.current); }, []);

  return (
    <div className="max-w-md mx-auto glass-card p-6 rounded-[2rem] border border-teal-500/10 flex flex-col items-center gap-6">
      <div className="w-full flex justify-between items-center text-xs font-mono font-bold select-none text-slate-350">
        <div>TIMER: <span className="text-teal-400 font-black text-sm">{time}s</span></div>
        <div>SCORE: <span className="text-teal-455 font-black text-sm">{score}</span></div>
      </div>
      <div className="flex flex-col items-center gap-4 bg-slate-950 p-6 rounded-2xl w-full border border-slate-900">
        <span className="text-[10px] font-mono tracking-widest text-slate-500 uppercase">Target Direction</span>
        <span className="text-xl font-black text-teal-400 uppercase tracking-widest font-mono">{targetDir}</span>
        <div className="text-6xl font-black text-slate-100 my-4 select-none">{arrowChars[currentArrow]}</div>
      </div>
      {isPlaying ? (
        <div className="grid grid-cols-2 gap-4 w-full">
          <button onClick={() => handleAnswer(true)} className="py-3.5 bg-emerald-900/10 hover:bg-emerald-600 border border-emerald-500/30 text-emerald-400 hover:text-white rounded-xl text-xs font-black uppercase tracking-wider transition-all cursor-pointer">
            Matches
          </button>
          <button onClick={() => handleAnswer(false)} className="py-3.5 bg-rose-900/10 hover:bg-rose-600 border border-rose-500/30 text-rose-455 hover:text-white rounded-xl text-xs font-black uppercase tracking-wider transition-all cursor-pointer">
            Mismatch
          </button>
        </div>
      ) : (
        <button onClick={startTest} className="w-full py-3.5 bg-gradient-to-r from-teal-500 to-teal-650 text-white font-black text-xs uppercase tracking-widest rounded-xl transition-all cursor-pointer">
          Start Game
        </button>
      )}
    </div>
  );
}

