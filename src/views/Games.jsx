// GAME 1: SCHULTE GRID
// ============================================================================
function SchulteGridGame() {
  const [grid, setGrid] = useState([]);
  const [nextNum, setNextNum] = useState(1);
  const [isPlaying, setIsPlaying] = useState(false);
  const [time, setTime] = useState(0);
  const [bestTime, setBestTime] = useState(() => parseFloat(localStorage.getItem('g_schulte_best') || '99.9'));
  const [isWon, setIsWon] = useState(false);
  const timerRef = useRef(null);

  const initGame = () => {
    const arr = Array.from({ length: 16 }, (_, i) => i + 1).sort(() => Math.random() - 0.5);
    setGrid(arr);
    setNextNum(1);
    setTime(0);
    setIsWon(false);
  };

  const startGame = () => {
    initGame();
    setIsPlaying(true);
    if (timerRef.current) clearInterval(timerRef.current);
    const start = Date.now();
    timerRef.current = setInterval(() => {
      setTime(parseFloat(((Date.now() - start) / 1000).toFixed(2)));
    }, 10);
  };

  const handleTile = (num) => {
    if (!isPlaying) return;
    if (num === nextNum) {
      if (num === 16) {
        clearInterval(timerRef.current);
        setIsPlaying(false);
        setIsWon(true);
        if (time < bestTime) {
          setBestTime(time);
          localStorage.setItem('g_schulte_best', String(time));
        }
      } else {
        setNextNum(num + 1);
      }
    }
  };

  useEffect(() => { initGame(); return () => clearInterval(timerRef.current); }, []);

  return (
    <div className="max-w-md mx-auto glass-card p-6 rounded-[2rem] border border-teal-500/10 flex flex-col items-center gap-6">
      <div className="w-full flex justify-between items-center text-xs font-mono font-bold select-none text-slate-350">
        <div>TIME: <span className="text-teal-400 text-lg font-black">{time.toFixed(2)}s</span></div>
        <div>BEST: <span className="text-slate-200 text-sm">{bestTime === 99.9 ? 'N/A' : `${bestTime}s`}</span></div>
        <div>TARGET: <span className="text-teal-455 text-lg font-black">{isWon ? '✔' : nextNum}</span></div>
      </div>
      <div className="grid grid-cols-4 gap-2.5 w-full aspect-square">
        {grid.map(n => (
          <button
            key={n}
            disabled={!isPlaying}
            onClick={() => handleTile(n)}
            className={`rounded-xl text-lg font-mono font-black border transition-all cursor-pointer ${
              n < nextNum ? 'bg-teal-950/10 border-teal-500/10 text-teal-500/20' :
              isPlaying && n === nextNum ? 'bg-teal-950/20 border-teal-400 text-teal-400 scale-95 shadow-md shadow-teal-500/10' :
              isPlaying ? 'bg-slate-955 border-slate-800 text-slate-200 hover:bg-slate-850' : 'bg-slate-955 border-slate-900 text-slate-600'
            }`}
          >
            {n}
          </button>
        ))}
      </div>
      <button onClick={startGame} className="w-full py-3.5 bg-gradient-to-r from-teal-500 to-teal-650 hover:from-teal-450 hover:to-teal-600 text-white font-black text-xs uppercase tracking-widest rounded-xl transition-all cursor-pointer shadow-md">
        {isWon ? 'Play Again' : 'Start Focus Run'}
      </button>
    </div>
  );
}

